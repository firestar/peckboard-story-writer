// Three-stage bundle, same shape as project-planner / graphify.
//
// Stage 0 embeds the vendored writing-lessons doc (docs/writing-lessons.md)
// into src/generated/lessons.ts as a JSON-escaped string constant, so the
// prompt pack (src/prompts/lessons.ts) can parse it without a filesystem
// read inside the sandbox.
//
// Stage 1 compiles the browser page (page/main.js) into a single minified IIFE
// and writes it into src/generated/pageBundle.ts as a JSON-escaped string
// constant — the page source may freely use backticks / `${`.
//
// Stage 2 is the standard plugin bundle: one CommonJS es2020 file that the
// Extism js-pdk compiler (`extism-js`) turns into the wasm plugin.
const esbuild = require("esbuild");
const fs = require("fs");

async function main() {
  fs.mkdirSync("src/generated", { recursive: true });

  const lessonsMd = fs.readFileSync("docs/writing-lessons.md", "utf8");
  fs.writeFileSync(
    "src/generated/lessons.ts",
    "// GENERATED by esbuild.js (stage 0) from docs/writing-lessons.md — do not edit, not committed.\n" +
      "export const LESSONS_MD: string = " +
      JSON.stringify(lessonsMd) +
      ";\n",
  );

  const page = await esbuild.build({
    entryPoints: ["page/main.js"],
    bundle: true,
    minify: true,
    format: "iife",
    target: ["es2020"],
    write: false,
    logLevel: "info",
  });
  const js = page.outputFiles[0].text;
  fs.writeFileSync(
    "src/generated/pageBundle.ts",
    "// GENERATED by esbuild.js (stage 1) — do not edit, not committed.\n" +
      "export const PAGE_JS: string = " +
      JSON.stringify(js) +
      ";\n",
  );

  await esbuild.build({
    entryPoints: ["src/index.ts"],
    outfile: "dist/index.js",
    bundle: true,
    sourcemap: false,
    minify: false,
    format: "cjs",
    target: ["es2020"],
    logLevel: "info",
  });
}

main().catch(() => process.exit(1));
